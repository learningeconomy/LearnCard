/**
 * Regenerates src/assets/fonts/self-hosted/ from the installed @fontsource packages (OFL-1.1).
 *
 * Only the faces the app's CSS references are vendored: the weights Tailwind classes use, the
 * italic weights `italic` resolves to, and the latin/latin-ext subsets. Run with
 * `bun scripts/vendor-fonts.ts` after bumping a @fontsource version.
 */
import { copyFileSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'fs';
import { createRequire } from 'module';
import { dirname, join, resolve } from 'path';

type Face = { family: string; pkg: string; weight: number; style: 'normal' | 'italic' };

const SUBSETS = ['latin-ext', 'latin'] as const;
const POPPINS_NORMAL = [300, 400, 500, 600, 700, 800, 900];
const POPPINS_ITALIC = [400, 500, 600, 700];

const FACES: Face[] = [
    ...POPPINS_NORMAL.map(weight => ({
        family: 'Poppins',
        pkg: 'poppins',
        weight,
        style: 'normal' as const,
    })),
    ...POPPINS_ITALIC.map(weight => ({
        family: 'Poppins',
        pkg: 'poppins',
        weight,
        style: 'italic' as const,
    })),
    { family: 'Jacques Francois', pkg: 'jacques-francois', weight: 400, style: 'normal' },
];

const appRoot = resolve(dirname(new URL(import.meta.url).pathname), '..');
const outDir = join(appRoot, 'src/assets/fonts/self-hosted');
const require = createRequire(join(appRoot, 'package.json'));
const pkgDir = (pkg: string) => dirname(require.resolve(`@fontsource/${pkg}/package.json`));

const unicodeRange = (
    pkg: string,
    subset: string,
    weight: number,
    style: string
): string | null => {
    const css = readFileSync(
        join(pkgDir(pkg), `${style === 'italic' ? `${weight}-italic` : weight}.css`),
        'utf8'
    );
    const block = css
        .split('/* ')
        .find(b => b.startsWith(`${pkg}-${subset}-${weight}-${style} */`));
    return block?.match(/unicode-range:\s*([^;]+);/)?.[1].trim() ?? null;
};

rmSync(outDir, { recursive: true, force: true });
mkdirSync(outDir, { recursive: true });

const rules: string[] = [];
const licenses = new Set<string>();
for (const face of FACES) {
    for (const subset of SUBSETS) {
        const file = `${face.pkg}-${subset}-${face.weight}-${face.style}.woff2`;
        const source = join(pkgDir(face.pkg), 'files', file);
        if (!existsSync(source)) continue;
        copyFileSync(source, join(outDir, file));
        licenses.add(face.pkg);
        const range = unicodeRange(face.pkg, subset, face.weight, face.style);
        rules.push(
            [
                '@font-face {',
                `    font-family: '${face.family}';`,
                `    font-style: ${face.style};`,
                '    font-display: swap;',
                `    font-weight: ${face.weight};`,
                `    src: url('./${file}') format('woff2');`,
                ...(range ? [`    unicode-range: ${range};`] : []),
                '}',
            ].join('\n')
        );
    }
}

for (const pkg of licenses) {
    copyFileSync(join(pkgDir(pkg), 'LICENSE'), join(outDir, `LICENSE-${pkg}.txt`));
}

writeFileSync(
    join(outDir, 'fonts.css'),
    `/* Generated by scripts/vendor-fonts.ts from @fontsource (OFL-1.1, see LICENSE-*.txt). Do not edit. */\n\n${rules.join('\n\n')}\n`
);
console.log(`${rules.length} faces written to ${outDir}`);
