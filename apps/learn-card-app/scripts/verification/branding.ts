import { readFile } from 'node:fs/promises';
import { extname, join } from 'node:path';
import type { Plugin } from 'vite';

import { APP_ROOT } from './constants';

const IMAGE_TYPES: Record<string, string> = {
    '.svg': 'image/svg+xml',
    '.png': 'image/png',
    '.jpg': 'image/jpeg',
    '.jpeg': 'image/jpeg',
    '.webp': 'image/webp',
    '.gif': 'image/gif',
    '.ico': 'image/x-icon',
    '.avif': 'image/avif',
};

/** Serve this verifier's LearnCard branding without generating shared public assets. */
export const verificationBrandingPlugin = (appRoot = APP_ROOT): Plugin => ({
    name: 'lc-verification-branding',
    enforce: 'pre',
    configureServer(server) {
        const directory = join(appRoot, 'environments/learncard/assets/branding');
        server.middlewares.use((request, response, next) => {
            const pathname = (request.url ?? '/').split('?')[0];
            if (!pathname.startsWith('/branding/')) return next();
            response.setHeader('Cache-Control', 'no-store');
            if (request.method !== 'GET' && request.method !== 'HEAD') {
                response.statusCode = 405;
                response.setHeader('Allow', 'GET, HEAD');
                response.end();
                return;
            }
            let filename: string;
            try {
                filename = decodeURIComponent(pathname.slice('/branding/'.length));
            } catch {
                response.statusCode = 400;
                response.end();
                return;
            }
            const contentType = IMAGE_TYPES[extname(filename).toLowerCase()];
            // Branding is a flat, image-only directory. Never expose other tenant files
            // or fall through to stale branding generated by an unrelated lc dev run.
            if (!/^[a-zA-Z0-9][a-zA-Z0-9._-]*$/.test(filename) || !contentType) {
                response.statusCode = 404;
                response.end();
                return;
            }
            void readFile(join(directory, filename)).then(
                bytes => {
                    response.setHeader('Content-Type', contentType);
                    response.setHeader('Content-Length', bytes.length);
                    response.end(request.method === 'HEAD' ? undefined : bytes);
                },
                error => {
                    if ((error as NodeJS.ErrnoException).code !== 'ENOENT') return next(error);
                    response.statusCode = 404;
                    response.end();
                }
            );
        });
    },
});
