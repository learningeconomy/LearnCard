export const capitalizeWordsAfterSpace = (str: string) =>
    str.replace(/\b\w/g, char => char.toUpperCase());

export const replaceWhiteSpacesWithUnderscores = (str: string) => str.trim().replace(/\s+/g, '_');

export const constructCustomType = (categoryType: string, customAchievementType: string) => {
    const capitalized = capitalizeWordsAfterSpace(customAchievementType);
    const transformed = replaceWhiteSpacesWithUnderscores(capitalized);
    return `ext:LCA_CUSTOM:${categoryType}:${transformed}`;
};
